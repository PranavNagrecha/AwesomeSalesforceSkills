def _survey_artefacts_present(manifest_dir: Path, settings_path: Path | None) -> list[str]:
    """Evidence that this tree ships surveys, other than the settings file itself."""
    evidence: list[str] = []

    surveys_dir = manifest_dir / "surveys"
    if surveys_dir.is_dir():
        for pattern in ("*.survey.json", "*.invitations.csv"):
            for path in sorted(surveys_dir.glob(pattern)):
                evidence.append(str(path.relative_to(manifest_dir)))

    flow_dir = manifest_dir / "flows"
    if flow_dir.is_dir():
        for flow_path in sorted(flow_dir.glob("*.flow-meta.xml")):
            root = _parse_xml(flow_path)
            if root is None:
                continue
            process_type = _text(root, "processType")
            if process_type in ("Survey", "SurveyEnrich", "CustomerLifecycle"):
                evidence.append(str(flow_path.relative_to(manifest_dir)))
                continue
            for action in root.findall(".//actionCalls"):
                action_type = _text(action, "actionType")
                if action_type in (
                    "sendSurveyInvitation",
                    "dynamicSendSurveyInvitation",
                    "performSurveySentimentAnalysis",
                ):
                    evidence.append(str(flow_path.relative_to(manifest_dir)))
                    break

    bpg_dir = manifest_dir / "businessProcessGroups"
    if bpg_dir.is_dir():
        for path in sorted(bpg_dir.glob("*.businessProcessGroup-meta.xml")):
            evidence.append(str(path.relative_to(manifest_dir)))

    if settings_path is not None:
        settings_rel = str(settings_path.relative_to(manifest_dir))
        evidence = [e for e in evidence if e != settings_rel]
    return evidence


def check_survey_settings(manifest_dir: Path) -> list[Finding]:
    """SurveySettings parses and enables Surveys when survey artefacts are present.

    File name and location are fixed: "SurveySettings values are stored in a single
    file named Survey.settings in the settings folder" (api_meta.txt L127618-127620).
    enableSurvey defaults to false (L127641-127642).
    """
    findings: list[Finding] = []
    settings_dir = manifest_dir / "settings"

    candidates = []
    if settings_dir.is_dir():
        for name in ("Survey.settings-meta.xml", "Survey.settings"):
            path = settings_dir / name
            if path.is_file():
                candidates.append(path)

    settings_path = candidates[0] if candidates else None
    artefacts = _survey_artefacts_present(manifest_dir, settings_path)

    if settings_path is None:
        if artefacts:
            findings.append(
                Finding(
                    "ERROR",
                    "settings/Survey.settings-meta.xml",
                    "missing, but the tree ships survey artefacts ("
                    + ", ".join(artefacts[:3])
                    + ("..." if len(artefacts) > 3 else "")
                    + "). enableSurvey defaults to false (api_meta.txt L127641-127642), "
                    "so the target org will reject or ignore them.",
                )
            )
        return findings

    where = str(settings_path.relative_to(manifest_dir))
    root = _parse_xml(settings_path)
    if root is None:
        findings.append(Finding("ERROR", where, "is not well-formed XML."))
        return findings

    if root.tag != "SurveySettings":
        findings.append(
            Finding(
                "ERROR",
                where,
                f"root element is <{root.tag}>, expected <SurveySettings> "
                "(api_meta.txt L127650-127658).",
            )
        )
        return findings

    enable = _text(root, "enableSurvey")
    if enable is None:
        findings.append(
            Finding(
                "ERROR" if artefacts else "WARN",
                where,
                "has no <enableSurvey> element; it defaults to false "
                "(api_meta.txt L127641-127642).",
            )
        )
    elif enable.lower() != "true":
        findings.append(
            Finding(
                "ERROR" if artefacts else "WARN",
                where,
                f"<enableSurvey> is {enable!r}. Surveys is off in the target org, so "
                "every survey artefact in this package is inert.",
            )
        )

    if _is_true(root, "enableSurveyOwnerCanManageResponse"):
        findings.append(
            Finding(
                "WARN",
                where,
                "<enableSurveyOwnerCanManageResponse> is true. Survey owners can then "
                "manage participant responses; the documented default is false "
                "(api_meta.txt L127644-127646). Confirm this is intended.",
            )
        )

    # BusinessProcessGroup is gated on Customer Lifecycle Maps (api_meta.txt L31301).
    bpg_dir = manifest_dir / "businessProcessGroups"
    has_bpg = bpg_dir.is_dir() and any(bpg_dir.glob("*.businessProcessGroup-meta.xml"))
    if has_bpg and not _is_true(root, "enableIndustriesCxmEnabled"):
        findings.append(
            Finding(
                "ERROR",
                where,
                "ships BusinessProcessGroup metadata but <enableIndustriesCxmEnabled> is "
                "not true. That type 'is available in orgs with Surveys enabled with the "
                "Customer Lifecycle Designer license' (api_meta.txt L31301).",
            )
        )

    return findings


