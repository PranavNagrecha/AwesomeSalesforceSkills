def check_flow_survey_references(manifest_dir: Path) -> list[Finding]:
    """Flows that create SurveyInvitation / SurveySubject records write valid fields."""
    findings: list[Finding] = []
    flow_dir = manifest_dir / "flows"
    if not flow_dir.is_dir():
        return findings

    for flow_path in sorted(flow_dir.glob("*.flow-meta.xml")):
        where = str(flow_path.relative_to(manifest_dir))
        root = _parse_xml(flow_path)
        if root is None:
            continue

        if _text(root, "processType") in ("Survey", "SurveyEnrich"):
            continue  # the survey itself, not automation around it

        for record_create in root.findall(".//recordCreates"):
            obj_name = _text(record_create, "object")
            if obj_name not in ("SurveyInvitation", "SurveySubject"):
                continue

            element_name = _text(record_create, "name") or "(unnamed)"
            assigned = set()
            for assignment in record_create.findall(".//inputAssignments"):
                field = _text(assignment, "field")
                if field is not None:
                    assigned.add(field)

            if obj_name == "SurveyInvitation":
                for bad_field, reason in INVITATION_DERIVED.items():
                    if bad_field in assigned:
                        findings.append(
                            Finding(
                                "ERROR",
                                where,
                                f"element '{element_name}' sets SurveyInvitation.{bad_field}, "
                                f"which is not createable -- {reason}.",
                            )
                        )
                unknown = assigned - INVITATION_CREATEABLE - set(INVITATION_DERIVED)
                for field in sorted(unknown):
                    findings.append(
                        Finding(
                            "WARN",
                            where,
                            f"element '{element_name}' sets SurveyInvitation.{field}, which is "
                            "not in the documented createable field list "
                            "(object_reference.txt L274594-274805).",
                        )
                    )
                for field in sorted(INVITATION_REQUIRED - assigned):
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"element '{element_name}' creates a SurveyInvitation without "
                            f"{field}.",
                        )
                    )
                if "ParticipantId" not in assigned:
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"element '{element_name}' creates a SurveyInvitation without "
                            "ParticipantId. ParticipantId is the only writable participant "
                            "field and is not updateable "
                            "(object_reference.txt L274729-274742), so the response can "
                            "never be tied to the recipient.",
                        )
                    )

            else:  # SurveySubject
                for field in sorted(SUBJECT_DERIVED & assigned):
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"element '{element_name}' sets SurveySubject.{field}, which "
                            "Salesforce derives and refuses on insert "
                            "(object_reference.txt L275987-275995, L275923-275926).",
                        )
                    )
                for field in sorted({"ParentId", "SubjectId"} - assigned):
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"element '{element_name}' creates a SurveySubject without "
                            f"{field}. ParentId must be the SurveyInvitation or "
                            "SurveyResponse Id and SubjectId the business record "
                            "(object_reference.txt L275898-275917).",
                        )
                    )

        for action in root.findall(".//actionCalls"):
            if _text(action, "actionType") == "exportSurveyResponses":
                findings.append(
                    Finding(
                        "ERROR",
                        where,
                        "calls 'exportSurveyResponses', which the Metadata API guide lists "
                        "under 'These values are reserved for future use' "
                        "(api_meta.txt L69583-69586).",
                    )
                )

    return findings


