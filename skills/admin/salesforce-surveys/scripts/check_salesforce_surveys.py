# object_reference.txt L274965-274989 -- SurveyQuestion.QuestionType restricted picklist.
QUESTION_TYPES = {
    "Boolean",            # API v49.0+
    "CSAT",
    "Currency",
    "Date",
    "DateTime",
    "FreeText",
    "Image",
    "Matrix",             # API v55.0+
    "MultipleChoice",
    "MultiSelectPicklist",
    "NPS",
    "Number",
    "Picklist",
    "RadioButton",
    "StackRank",
    "Rating",
    "ShortText",          # API v49.0+
    "Slider",
    "Toggle",
}

# api_meta.txt L31309-31338 -- Metadata API SurveyQuestionType enum. Same domain,
# different spelling for the multiple-choice value; RadioButton is absent.
METADATA_ENUM_ONLY = {"MultiChoice"}

# Question types that carry a numeric answer in SurveyQuestionResponse.NumberValue
# (object_reference.txt L275217-275230).
NUMERIC_QUESTION_TYPES = {"NPS", "Rating", "Slider", "CSAT", "Number"}

# object_reference.txt L274594-274805 -- the only createable SurveyInvitation fields.
INVITATION_CREATEABLE = {
    "Name",
    "SurveyId",
    "ParticipantId",
    "CommunityId",
    "EmailBrandingId",
    "OwnerId",
    "IsDefault",
    "InviteExpiryDateTime",
    "OptionsAllowGuestUserResponse",
    "OptionsAllowParticipantAccessTheirResponse",
    "OptionsCollectAnonymousResponse",
}
INVITATION_REQUIRED = {"Name", "SurveyId"}

# Derived / read-only on SurveyInvitation: setting these fails at run time.
# ContactId/LeadId/UserId  object_reference.txt L274609, L274673, L274791
# InvitationLink           L274624-274631
# ResponseStatus           L274736-274783
INVITATION_DERIVED = {
    "ContactId": "derived from ParticipantId (object_reference.txt L274609)",
    "LeadId": "derived from ParticipantId (object_reference.txt L274673)",
    "UserId": "derived from ParticipantId (object_reference.txt L274791)",
    "InvitationLink": "generated by the platform (object_reference.txt L274624-274631)",
    "ResponseStatus": "read-only picklist (object_reference.txt L274736-274783)",
}

# SurveySubject: SurveyId and SubjectEntityType are derived
# (object_reference.txt L275987-275995, L275923-275926).
SUBJECT_DERIVED = {"SurveyId", "SubjectEntityType"}

SURVEY_OBJECTS = [
    "Survey",
    "SurveyInvitation",
    "SurveyResponse",
    "SurveyQuestionResponse",
    "SurveyQuestionScore",
    "SurveySubject",
]

REQUIRED_GUEST_PERMS = {
    "Survey": {"allowRead"},
    "SurveyInvitation": {"allowRead", "allowCreate"},
    "SurveyResponse": {"allowRead", "allowCreate"},
    "SurveyQuestionResponse": {"allowRead", "allowCreate"},
}


class Finding:
    """One issue. severity is 'ERROR' or 'WARN'."""

    __slots__ = ("severity", "where", "message")

    def __init__(self, severity: str, where: str, message: str) -> None:
        self.severity = severity
        self.where = where
        self.message = message

    def __str__(self) -> str:
        return f"{self.severity}: {self.where}: {self.message}"


# ---------------------------------------------------------------------------
# XML helpers.  NEVER use `elem.find(a) or elem.find(b)` -- a leaf Element is
# falsy in ElementTree, so an empty <allowRead/> would be treated as missing.
# ---------------------------------------------------------------------------


def _parse_xml(path: Path) -> ET.Element | None:
    """Parse XML and strip namespace prefixes so plain tag names match."""
    try:
        root = ET.parse(path).getroot()
    except (ET.ParseError, OSError):
        return None
    for elem in root.iter():
        if isinstance(elem.tag, str) and "}" in elem.tag:
            elem.tag = elem.tag.split("}", 1)[1]
    return root


def _child(parent: ET.Element, tag: str) -> ET.Element | None:
    """Return the first child with `tag`, or None. Explicit is-not-None test."""
    found = parent.find(tag)
    if found is not None:
        return found
    return None


def _text(parent: ET.Element | None, tag: str) -> str | None:
    """Text of the first `tag` child, stripped; None when absent or empty."""
    if parent is None:
        return None
    node = _child(parent, tag)
    if node is None:
        return None
    if node.text is None:
        return None
    value = node.text.strip()
    return value if value else None


def _is_true(parent: ET.Element, tag: str) -> bool:
    value = _text(parent, tag)
    return value is not None and value.lower() == "true"


