def check_guest_user_profiles(manifest_dir: Path) -> list[Finding]:
    """Guest profiles grant the survey object permissions and nothing broader."""
    findings: list[Finding] = []
    profile_dir = manifest_dir / "profiles"
    if not profile_dir.is_dir():
        return findings

    guest_profiles = [
        path
        for path in sorted(profile_dir.glob("*.profile-meta.xml"))
        if "guest" in path.stem.lower()
    ]

    for profile_path in guest_profiles:
        where = str(profile_path.relative_to(manifest_dir))
        root = _parse_xml(profile_path)
        if root is None:
            findings.append(Finding("ERROR", where, "is not well-formed XML."))
            continue

        granted: dict[str, set[str]] = {}
        for obj_perm in root.findall(".//objectPermissions"):
            obj_name = _text(obj_perm, "object")
            if obj_name is None or obj_name not in SURVEY_OBJECTS:
                continue
            granted.setdefault(obj_name, set())
            for perm_tag in ("allowRead", "allowCreate", "allowEdit", "allowDelete"):
                if _is_true(obj_perm, perm_tag):
                    granted[obj_name].add(perm_tag)
            for broad in ("viewAllRecords", "modifyAllRecords"):
                if _is_true(obj_perm, broad):
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"grants {broad} on {obj_name}. A guest profile must never hold "
                            "an all-records permission on survey data.",
                        )
                    )

        if not granted:
            continue  # profile does not touch survey objects at all

        for obj, required in REQUIRED_GUEST_PERMS.items():
            missing = required - granted.get(obj, set())
            if missing:
                findings.append(
                    Finding(
                        "ERROR",
                        where,
                        f"missing {', '.join(sorted(missing))} on {obj}. External survey "
                        "respondents fail silently on submit.",
                    )
                )

        if "allowCreate" in granted.get("Survey", set()):
            findings.append(
                Finding(
                    "WARN",
                    where,
                    "grants allowCreate on Survey. The Survey object has no create() call "
                    "(object_reference.txt L274221-274223), so this widens the audit "
                    "surface without enabling anything.",
                )
            )

    return findings


