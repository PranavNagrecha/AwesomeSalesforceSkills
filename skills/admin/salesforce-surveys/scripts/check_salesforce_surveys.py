def _lint_survey_design(path: Path, where: str) -> list[Finding]:
    findings: list[Finding] = []
    try:
        design = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as exc:
        return [Finding("ERROR", where, f"is not valid JSON: {exc}")]

    if not isinstance(design, dict):
        return [Finding("ERROR", where, "top level must be a JSON object.")]

    survey_type = str(design.get("surveyType", "SURVEY")).upper()
    if survey_type not in ("SURVEY", "BASIC", "ASSESSMENT"):
        findings.append(
            Finding(
                "ERROR",
                where,
                f"surveyType {survey_type!r} is not one of SURVEY, BASIC, ASSESSMENT "
                "(object_reference.txt L274354-274359).",
            )
        )

    anonymous = bool(design.get("collectAnonymousResponse", False))
    allow_guest = bool(design.get("allowGuestUserResponse", False))
    allow_access = bool(design.get("allowParticipantsAccessTheirResponse", False))
    partial_save = bool(design.get("isPartialSaveEnabled", False))

    pages = design.get("pages")
    if not isinstance(pages, list) or not pages:
        return findings + [Finding("ERROR", where, "has no 'pages' array.")]

    page_names: list[str] = []
    for index, page in enumerate(pages):
        if not isinstance(page, dict):
            findings.append(Finding("ERROR", where, f"pages[{index}] is not an object."))
            continue
        name = page.get("name")
        if not name:
            findings.append(Finding("ERROR", where, f"pages[{index}] has no 'name'."))
            continue
        if name in page_names:
            findings.append(Finding("ERROR", where, f"duplicate page name {name!r}."))
        page_names.append(str(name))

    known_pages = set(page_names)

    for page in pages:
        if not isinstance(page, dict):
            continue
        page_name = str(page.get("name", "?"))
        questions = page.get("questions", [])
        if not isinstance(questions, list):
            findings.append(
                Finding("ERROR", where, f"page {page_name!r}: 'questions' must be a list.")
            )
            continue

        branching_questions = 0
        for question in questions:
            if not isinstance(question, dict):
                findings.append(
                    Finding("ERROR", where, f"page {page_name!r}: a question is not an object.")
                )
                continue
            q_name = str(question.get("name", "(unnamed)"))
            q_type = question.get("type")

            if q_type is None:
                findings.append(
                    Finding(
                        "ERROR",
                        where,
                        f"page {page_name!r}, question {q_name!r} has no 'type'.",
                    )
                )
            elif q_type in METADATA_ENUM_ONLY:
                findings.append(
                    Finding(
                        "ERROR",
                        where,
                        f"page {page_name!r}, question {q_name!r} uses {q_type!r}, the "
                        "Metadata API SurveyQuestionType spelling (api_meta.txt "
                        "L31309-31338). SurveyQuestion.QuestionType spells it "
                        "'MultipleChoice' (object_reference.txt L274965-274989).",
                    )
                )
            elif q_type not in QUESTION_TYPES:
                findings.append(
                    Finding(
                        "ERROR",
                        where,
                        f"page {page_name!r}, question {q_name!r} has type {q_type!r}, which "
                        "is not a SurveyQuestion.QuestionType value "
                        "(object_reference.txt L274965-274989).",
                    )
                )

            if "required" not in question:
                findings.append(
                    Finding(
                        "WARN",
                        where,
                        f"page {page_name!r}, question {q_name!r} does not state 'required'. "
                        "Whether a skip is possible changes how the response reads.",
                    )
                )

            branches = question.get("branches", [])
            if branches:
                branching_questions += 1
            if not isinstance(branches, list):
                findings.append(
                    Finding(
                        "ERROR",
                        where,
                        f"page {page_name!r}, question {q_name!r}: 'branches' must be a list.",
                    )
                )
                continue
            for branch in branches:
                if not isinstance(branch, dict):
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"page {page_name!r}, question {q_name!r}: a branch is not an "
                            "object.",
                        )
                    )
                    continue
                target = branch.get("goToPage")
                if not target:
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"page {page_name!r}, question {q_name!r}: a branch has no "
                            "'goToPage'.",
                        )
                    )
                elif str(target) not in known_pages:
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"page {page_name!r}, question {q_name!r}: branch target "
                            f"{target!r} is not a page in this survey.",
                        )
                    )
                elif str(target) == page_name:
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"page {page_name!r}, question {q_name!r}: branch targets its own "
                            "page, which loops the respondent.",
                        )
                    )

        if branching_questions and survey_type == "BASIC":
            findings.append(
                Finding(
                    "ERROR",
                    where,
                    f"page {page_name!r} defines branching, but surveyType is BASIC -- a "
                    "BASIC survey ships 'without inserted participant responses, display "
                    "logic, and page branching logic' "
                    "(object_reference.txt L274354-274359).",
                )
            )
        if branching_questions > 1:
            findings.append(
                Finding(
                    "ERROR",
                    where,
                    f"page {page_name!r} has {branching_questions} branching questions. "
                    "Routing is decided per page, so two questions on one page cannot send "
                    "the respondent to different places.",
                )
            )

    # Anonymity vs identity consistency.
    if anonymous and not allow_guest:
        findings.append(
            Finding(
                "WARN",
                where,
                "collectAnonymousResponse is true but allowGuestUserResponse is false. "
                "Anonymous collection normally implies unauthenticated respondents; "
                "confirm the audience.",
            )
        )
    if anonymous and design.get("associateSubjectRecord"):
        findings.append(
            Finding(
                "ERROR",
                where,
                "collectAnonymousResponse is true while associateSubjectRecord is set. "
                "An anonymous response cannot be traced to the participant, so the "
                "SurveySubject join gives a false sense of attribution.",
            )
        )
    if partial_save and (anonymous or allow_access):
        findings.append(
            Finding(
                "ERROR",
                where,
                "isPartialSaveEnabled is true, but Paused 'isn't available for invitations "
                "in which either OptionsAllowParticipantAccessTheirResponse or "
                "OptionsCollectAnonymousResponse is true' "
                "(object_reference.txt L274762-274766). Respondents cannot resume.",
            )
        )

    return findings


def check_survey_designs(manifest_dir: Path) -> list[Finding]:
    findings: list[Finding] = []
    surveys_dir = manifest_dir / "surveys"
    if not surveys_dir.is_dir():
        return findings
    for path in sorted(surveys_dir.glob("*.survey.json")):
        findings.extend(_lint_survey_design(path, str(path.relative_to(manifest_dir))))
    return findings


