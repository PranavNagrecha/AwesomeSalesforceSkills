def _parse_datetime(value: str) -> _dt.datetime | None:
    raw = value.strip()
    if not raw:
        return None
    if raw.endswith("Z"):
        raw = raw[:-1] + "+00:00"
    for parser in (
        lambda v: _dt.datetime.fromisoformat(v),
        lambda v: _dt.datetime.strptime(v, "%Y-%m-%d %H:%M:%S"),
        lambda v: _dt.datetime.strptime(v, "%Y-%m-%d"),
    ):
        try:
            parsed = parser(raw)
        except ValueError:
            continue
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=_dt.timezone.utc)
        return parsed
    return None


def check_invitation_csvs(manifest_dir: Path) -> list[Finding]:
    """SurveyInvitation load files use only createable columns with a future expiry."""
    findings: list[Finding] = []
    surveys_dir = manifest_dir / "surveys"
    if not surveys_dir.is_dir():
        return findings

    now = _dt.datetime.now(_dt.timezone.utc)

    for path in sorted(surveys_dir.glob("*.invitations.csv")):
        where = str(path.relative_to(manifest_dir))
        try:
            with path.open(newline="", encoding="utf-8-sig") as handle:
                reader = csv.DictReader(handle)
                headers = [h.strip() for h in (reader.fieldnames or [])]
                rows = list(reader)
        except (OSError, csv.Error) as exc:
            findings.append(Finding("ERROR", where, f"could not be read as CSV: {exc}"))
            continue

        if not headers:
            findings.append(Finding("ERROR", where, "has no header row."))
            continue

        for field in sorted(INVITATION_REQUIRED - set(headers)):
            findings.append(
                Finding(
                    "ERROR",
                    where,
                    f"missing required column {field!r} "
                    "(object_reference.txt L274594-274805).",
                )
            )
        if "ParticipantId" not in headers:
            findings.append(
                Finding(
                    "ERROR",
                    where,
                    "missing 'ParticipantId'. It is the only writable participant field and "
                    "cannot be added later -- it has Create but not Update "
                    "(object_reference.txt L274729-274742).",
                )
            )

        for header in headers:
            if header in INVITATION_DERIVED:
                findings.append(
                    Finding(
                        "ERROR",
                        where,
                        f"column {header!r} is not createable -- "
                        f"{INVITATION_DERIVED[header]}. The load will fail or drop it.",
                    )
                )
            elif header not in INVITATION_CREATEABLE:
                findings.append(
                    Finding(
                        "WARN",
                        where,
                        f"column {header!r} is not in the documented createable field list "
                        "for SurveyInvitation (object_reference.txt L274594-274805).",
                    )
                )

        if not rows:
            findings.append(Finding("WARN", where, "has a header but no data rows."))

        for line_no, row in enumerate(rows, start=2):
            for field in INVITATION_REQUIRED | {"ParticipantId"}:
                if field in headers and not (row.get(field) or "").strip():
                    findings.append(
                        Finding("ERROR", where, f"row {line_no}: {field} is blank.")
                    )

            expiry_raw = (row.get("InviteExpiryDateTime") or "").strip()
            if expiry_raw:
                expiry = _parse_datetime(expiry_raw)
                if expiry is None:
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"row {line_no}: InviteExpiryDateTime {expiry_raw!r} is not a "
                            "parseable date-time.",
                        )
                    )
                elif expiry <= now:
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"row {line_no}: InviteExpiryDateTime {expiry_raw} is in the "
                            "past; the invitation is dead on arrival.",
                        )
                    )

            anon = (row.get("OptionsCollectAnonymousResponse") or "").strip().lower()
            access = (
                row.get("OptionsAllowParticipantAccessTheirResponse") or ""
            ).strip().lower()
            guest = (row.get("OptionsAllowGuestUserResponse") or "").strip().lower()

            for field, value in (
                ("OptionsCollectAnonymousResponse", anon),
                ("OptionsAllowParticipantAccessTheirResponse", access),
                ("OptionsAllowGuestUserResponse", guest),
                ("IsDefault", (row.get("IsDefault") or "").strip().lower()),
            ):
                if value and value not in ("true", "false"):
                    findings.append(
                        Finding(
                            "ERROR",
                            where,
                            f"row {line_no}: {field} is {value!r}; expected true or false.",
                        )
                    )

            if anon == "true" and (row.get("ParticipantId") or "").strip():
                findings.append(
                    Finding(
                        "WARN",
                        where,
                        f"row {line_no}: OptionsCollectAnonymousResponse is true while a "
                        "ParticipantId is supplied. The response will not be attributable, "
                        "and Paused is unavailable "
                        "(object_reference.txt L274762-274766).",
                    )
                )

    return findings


