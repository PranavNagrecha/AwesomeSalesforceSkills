def check_salesforce_surveys(manifest_dir: Path) -> list[Finding]:
    findings: list[Finding] = []
    findings.extend(check_survey_settings(manifest_dir))
    findings.extend(check_guest_user_profiles(manifest_dir))
    findings.extend(check_flow_survey_references(manifest_dir))
    findings.extend(check_survey_designs(manifest_dir))
    findings.extend(check_invitation_csvs(manifest_dir))
    return findings


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Check Salesforce Surveys configuration and metadata for common issues.",
    )
    parser.add_argument(
        "--manifest-dir",
        default=".",
        help="Root of the Salesforce metadata directory (default: current directory).",
    )
    parser.add_argument(
        "--warnings-as-errors",
        action="store_true",
        help="Exit 1 when only warnings were found.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    manifest_dir = Path(args.manifest_dir)

    if not manifest_dir.is_dir():
        print(f"ERROR: manifest directory not found: {manifest_dir}")
        return 2

    findings = check_salesforce_surveys(manifest_dir)
    errors = [f for f in findings if f.severity == "ERROR"]
    warnings = [f for f in findings if f.severity == "WARN"]

    for finding in findings:
        print(finding)

    print(f"\n{len(errors)} error(s), {len(warnings)} warning(s).")

    if errors:
        return 1
    if warnings and args.warnings_as_errors:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
