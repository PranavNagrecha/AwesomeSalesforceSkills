#!/usr/bin/env python3
"""Checker script for the Salesforce Surveys skill.

Scans a Salesforce metadata directory (plus the record-level artefacts this skill
produces) for survey configuration mistakes that deploy cleanly and then fail in
production:

  1. SurveySettings  -- settings/Survey.settings-meta.xml parses, uses the right
     root element, and has <enableSurvey>true</enableSurvey> whenever any other
     survey artefact is present in the tree.
  2. Guest user profiles -- object permissions for external survey respondents,
     and over-broad viewAllRecords / modifyAllRecords on survey objects.
  3. Flows -- record-triggered flows that create SurveyInvitation records without
     ParticipantId, and flows that write fields Salesforce derives and refuses.
  4. Survey design JSON -- surveys/*.survey.json design docs: every question has a
     valid type, every branch target resolves to a real page, and the
     anonymous/identified choice is consistent with guest access.
  5. Invitation CSV -- surveys/*.invitations.csv: required columns present, no
     non-createable columns, expiry parses and is in the future.

Grounding for every rule is cited inline against the Summer '26 / v62 PDF text.

Uses stdlib only -- no pip dependencies.

Usage:
    python3 check_salesforce_surveys.py --manifest-dir force-app/main/default
    python3 check_salesforce_surveys.py --manifest-dir force-app/main/default --warnings-as-errors

Exit codes:
    0  no errors
    1  one or more errors
    2  the manifest directory does not exist
"""

